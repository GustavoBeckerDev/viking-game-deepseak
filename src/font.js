export function textWidth(text, scale = 1) {
  return text.length * 6 * scale - scale;
}

export function drawText(ctx, text, x, y, color, scale = 1, shadow = null) {
  const str = String(text);
  let cursor = Math.round(x);
  const top = Math.round(y);
  for (const ch of str) {
    const glyph = GLYPHS[ch] || GLYPHS[' '];
    if (shadow) {
      paintGlyph(ctx, glyph, cursor + scale, top + scale, shadow, scale);
    }
    paintGlyph(ctx, glyph, cursor, top, color, scale);
    cursor += 6 * scale;
  }
}

function paintGlyph(ctx, glyph, x, y, color, scale) {
  ctx.fillStyle = color;
  for (let row = 0; row < 7; row++) {
    const line = glyph[row];
    for (let col = 0; col < 5; col++) {
      if (line[col] === '1') {
        ctx.fillRect(x + col * scale, y + row * scale, scale, scale);
      }
    }
  }
}
